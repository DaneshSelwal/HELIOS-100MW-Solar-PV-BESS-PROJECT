"""Render real Word documents (letters, reports, MOMs, plans) with python-docx."""
from __future__ import annotations
import datetime as dt, pathlib
from docx import Document
from docx.shared import Pt, Cm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT

NAVY = RGBColor(0x1F, 0x3A, 0x5F)


def _base(title: str, docnum: str, org: str, date: dt.date, rev: str | None = None, status: str | None = None) -> Document:
    doc = Document()
    for s in doc.sections:
        s.top_margin = s.bottom_margin = Cm(2); s.left_margin = s.right_margin = Cm(2.2)
    st = doc.styles["Normal"]; st.font.name = "Calibri"; st.font.size = Pt(10.5)
    # header band
    hdr = doc.sections[0].header.paragraphs[0]
    hdr.text = f"{org}    |    HELIOS 100 MW Solar PV + BESS (HEL001)    |    {docnum}"
    hdr.runs[0].font.size = Pt(8); hdr.runs[0].font.color.rgb = NAVY
    ftr = doc.sections[0].footer.paragraphs[0]
    ftr.text = "Fictional project generated by the HELIOS simulation. Not a real document."
    ftr.runs[0].font.size = Pt(7); ftr.alignment = WD_ALIGN_PARAGRAPH.CENTER
    t = doc.add_paragraph(); r = t.add_run(title); r.bold = True; r.font.size = Pt(16); r.font.color.rgb = NAVY
    meta = doc.add_table(rows=0, cols=4); meta.style = "Light Grid Accent 1"; meta.alignment = WD_TABLE_ALIGNMENT.CENTER
    row = meta.add_row().cells
    row[0].text, row[1].text, row[2].text, row[3].text = "Document No.", docnum, "Date", date.strftime("%d %b %Y")
    if rev is not None or status is not None:
        row = meta.add_row().cells
        row[0].text, row[1].text, row[2].text, row[3].text = "Revision", str(rev or "-"), "Status", str(status or "-")
    doc.add_paragraph()
    return doc


def _add_body(doc: Document, sections: list[dict]) -> None:
    """sections: [{heading, paragraphs:[str], bullets:[str], table:{columns:[...], rows:[[...]]}}]"""
    for s in sections:
        if s.get("heading"):
            h = doc.add_heading(s["heading"], level=2)
            for r in h.runs: r.font.color.rgb = NAVY
        for p in s.get("paragraphs", []) or []:
            doc.add_paragraph(p)
        for b in s.get("bullets", []) or []:
            doc.add_paragraph(b, style="List Bullet")
        tb = s.get("table")
        if tb and tb.get("columns"):
            cols = tb["columns"]; t = doc.add_table(rows=1, cols=len(cols)); t.style = "Light Grid Accent 1"
            for i, c in enumerate(cols):
                t.rows[0].cells[i].text = str(c)
                for p in t.rows[0].cells[i].paragraphs:
                    for r in p.runs: r.bold = True; r.font.size = Pt(9)
            for row in tb.get("rows", []):
                cells = t.add_row().cells
                for i in range(len(cols)):
                    cells[i].text = str(row[i]) if i < len(row) else ""
                    for p in cells[i].paragraphs:
                        for r in p.runs: r.font.size = Pt(9)
            doc.add_paragraph()


def document(path: pathlib.Path, *, title: str, docnum: str, org: str, date: dt.date, sections: list[dict],
             rev: str = "A", status: str = "Issued for Review", prepared_by: str = "", checked_by: str = "",
             approved_by: str = "") -> pathlib.Path:
    doc = _base(title, docnum, org, date, rev, status)
    _add_body(doc, sections)
    if prepared_by or approved_by:
        doc.add_paragraph()
        t = doc.add_table(rows=2, cols=3); t.style = "Light Grid Accent 1"
        for i, lab in enumerate(["Prepared by", "Checked by", "Approved by"]):
            t.rows[0].cells[i].text = lab
        t.rows[1].cells[0].text = prepared_by; t.rows[1].cells[1].text = checked_by; t.rows[1].cells[2].text = approved_by
    path.parent.mkdir(parents=True, exist_ok=True); doc.save(str(path)); return path


def letter(path: pathlib.Path, *, ref: str, date: dt.date, from_org: str, from_person: str, from_title: str,
           to_org: str, to_person: str, to_title: str, subject: str, body_paragraphs: list[str],
           cc: list[str] | None = None, attachments: list[str] | None = None, reply_to_ref: str | None = None) -> pathlib.Path:
    doc = Document()
    for s in doc.sections:
        s.top_margin = s.bottom_margin = Cm(2); s.left_margin = s.right_margin = Cm(2.5)
    st = doc.styles["Normal"]; st.font.name = "Calibri"; st.font.size = Pt(11)
    p = doc.add_paragraph(); r = p.add_run(from_org); r.bold = True; r.font.size = Pt(14); r.font.color.rgb = NAVY
    doc.add_paragraph("Project: HELIOS 100 MW Solar PV + BESS Power Plant (HEL001)").runs[0].font.size = Pt(9)
    ftr = doc.sections[0].footer.paragraphs[0]
    ftr.text = "Fictional correspondence generated by the HELIOS simulation."; ftr.runs[0].font.size = Pt(7)
    doc.add_paragraph()
    doc.add_paragraph(f"Our ref: {ref}" + (f"        Your ref: {reply_to_ref}" if reply_to_ref else ""))
    doc.add_paragraph(f"Date: {date.strftime('%d %B %Y')}")
    doc.add_paragraph()
    doc.add_paragraph(f"To:\t{to_person}\n\t{to_title}\n\t{to_org}")
    doc.add_paragraph()
    p = doc.add_paragraph(); r = p.add_run(f"Subject: {subject}"); r.bold = True
    doc.add_paragraph()
    doc.add_paragraph(f"Dear {to_person.split()[0] if to_person else 'Sir/Madam'},")
    for para in body_paragraphs:
        doc.add_paragraph(para)
    doc.add_paragraph()
    doc.add_paragraph("Yours sincerely,")
    doc.add_paragraph()
    p = doc.add_paragraph(); r = p.add_run(from_person); r.bold = True
    doc.add_paragraph(f"{from_title}\n{from_org}")
    if cc:
        doc.add_paragraph("cc: " + "; ".join(cc)).runs[0].font.size = Pt(9)
    if attachments:
        doc.add_paragraph("Attachments: " + "; ".join(attachments)).runs[0].font.size = Pt(9)
    path.parent.mkdir(parents=True, exist_ok=True); doc.save(str(path)); return path


def mom(path: pathlib.Path, *, ref: str, title: str, date: dt.date, venue: str, chaired_by: str, attendees: list[str],
        items: list[dict], actions: list[dict], org: str, next_meeting: str = "") -> pathlib.Path:
    """items: [{no, topic, discussion}], actions: [{no, action, owner, due, status}]"""
    doc = _base(title, ref, org, date)
    doc.add_paragraph(f"Venue: {venue}        Chaired by: {chaired_by}")
    doc.add_paragraph("Attendees: " + "; ".join(attendees))
    _add_body(doc, [{"heading": "Discussion",
                     "table": {"columns": ["No.", "Topic", "Discussion / Decision"],
                               "rows": [[i.get("no", k + 1), i.get("topic", ""), i.get("discussion", "")] for k, i in enumerate(items)]}},
                    {"heading": "Actions",
                     "table": {"columns": ["No.", "Action", "Owner", "Due", "Status"],
                               "rows": [[a.get("no", k + 1), a.get("action", ""), a.get("owner", ""), a.get("due", ""), a.get("status", "Open")] for k, a in enumerate(actions)]}}])
    if next_meeting:
        doc.add_paragraph(f"Next meeting: {next_meeting}")
    path.parent.mkdir(parents=True, exist_ok=True); doc.save(str(path)); return path
