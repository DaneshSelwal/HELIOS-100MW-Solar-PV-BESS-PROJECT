"""PDF output. Uses LibreOffice (soffice) for docx->pdf when available; otherwise a simple reportlab renderer."""
from __future__ import annotations
import pathlib, shutil, subprocess
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib import colors


def soffice() -> str | None:
    for c in ("soffice", "/Applications/LibreOffice.app/Contents/MacOS/soffice"):
        if shutil.which(c) or pathlib.Path(c).exists():
            return c
    return None


def docx_to_pdf(docx_path: pathlib.Path) -> pathlib.Path | None:
    exe = soffice()
    if not exe:
        return None
    subprocess.run([exe, "--headless", "--convert-to", "pdf", "--outdir", str(docx_path.parent), str(docx_path)],
                   capture_output=True, timeout=180)
    out = docx_path.with_suffix(".pdf")
    return out if out.exists() else None


def simple(path: pathlib.Path, *, title: str, docnum: str, date_str: str, sections: list[dict]) -> pathlib.Path:
    """Fallback PDF straight from structured sections (same shape as render.docx.document)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    ss = getSampleStyleSheet(); story = [Paragraph(title, ss["Title"]), Paragraph(f"{docnum} — {date_str}", ss["Normal"]), Spacer(1, 0.4 * cm)]
    for s in sections:
        if s.get("heading"): story.append(Paragraph(s["heading"], ss["Heading2"]))
        for p in s.get("paragraphs", []) or []: story.append(Paragraph(p, ss["Normal"]))
        for b in s.get("bullets", []) or []: story.append(Paragraph("• " + b, ss["Normal"]))
        tb = s.get("table")
        if tb and tb.get("columns"):
            data = [tb["columns"]] + [[str(c) for c in r] for r in tb.get("rows", [])]
            t = Table(data, repeatRows=1); t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.3, colors.grey),
                                                                   ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1F3A5F")),
                                                                   ("TEXTCOLOR", (0, 0), (-1, 0), colors.white), ("FONTSIZE", (0, 0), (-1, -1), 7)]))
            story.append(t); story.append(Spacer(1, 0.3 * cm))
    story.append(Spacer(1, 0.5 * cm)); story.append(Paragraph("Fictional project generated by the HELIOS simulation.", ss["Italic"]))
    SimpleDocTemplate(str(path), pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm, topMargin=2 * cm, bottomMargin=2 * cm).build(story)
    return path
